-- ============================================================
-- MUSICBOND — Μυστικό όνομα ομάδας για το Jam (SonoBus)
-- Τρέξε το ΜΕΤΑ το 004_rooms.sql.
--
-- Κάθε δωμάτιο παίρνει ένα τυχαίο μυστικό. Το όνομα της ομάδας στο SonoBus
-- γίνεται musicbond-<μυστικό>. Το βλέπει όποιος μπορεί να διαβάσει το δωμάτιο:
-- ο ιδιοκτήτης πάντα, οι άλλοι μόνο αν το δωμάτιο είναι δημόσιο.
-- ============================================================

alter table rooms
  add column if not exists jam_secret text
  not null default substr(md5(gen_random_uuid()::text), 1, 16);
